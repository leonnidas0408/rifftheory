-- Monitor de acessos anônimo e baseado em consentimento.
-- Não armazena IP, nome, e-mail ou identificadores de conta.

create table if not exists public.access_devices (
    device_id text primary key check (char_length(device_id) between 16 and 128),
    first_seen timestamptz not null default timezone('utc', now()),
    last_seen timestamptz not null default timezone('utc', now()),
    total_entries integer not null default 0 check (total_entries >= 0),
    total_sessions integer not null default 0 check (total_sessions >= 0),
    last_path text,
    user_agent text,
    consented_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.access_sessions (
    device_id text not null references public.access_devices(device_id) on delete cascade,
    session_id text not null check (char_length(session_id) between 16 and 128),
    started_at timestamptz not null default timezone('utc', now()),
    primary key (device_id, session_id)
);

create table if not exists public.access_visits (
    id bigint generated by default as identity primary key,
    device_id text not null references public.access_devices(device_id) on delete cascade,
    session_id text not null,
    visited_at timestamptz not null default timezone('utc', now()),
    path text,
    user_agent text,
    constraint access_visits_session_fk foreign key (device_id, session_id)
        references public.access_sessions(device_id, session_id) on delete cascade
);

create index if not exists access_visits_device_time_idx
    on public.access_visits (device_id, visited_at desc);

alter table public.access_devices enable row level security;
alter table public.access_sessions enable row level security;
alter table public.access_visits enable row level security;

-- O navegador não recebe permissão de leitura: o painel usa o SQL Editor do Supabase.
drop policy if exists access_devices_no_public_read on public.access_devices;
drop policy if exists access_sessions_no_public_read on public.access_sessions;
drop policy if exists access_visits_no_public_read on public.access_visits;
create policy access_devices_no_public_read on public.access_devices for select using (false);
create policy access_sessions_no_public_read on public.access_sessions for select using (false);
create policy access_visits_no_public_read on public.access_visits for select using (false);

create or replace function public.register_anonymous_access(
    p_device_id text,
    p_session_id text,
    p_path text default null,
    p_user_agent text default null
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
    v_now timestamptz := timezone('utc', now());
begin
    if p_device_id is null or char_length(p_device_id) < 16 or char_length(p_device_id) > 128 then
        raise exception 'invalid device id';
    end if;
    if p_session_id is null or char_length(p_session_id) < 16 or char_length(p_session_id) > 128 then
        raise exception 'invalid session id';
    end if;

    insert into public.access_devices (device_id, first_seen, last_seen, total_entries, last_path, user_agent, consented_at)
    values (p_device_id, v_now, v_now, 1, left(p_path, 512), left(p_user_agent, 512), v_now)
    on conflict (device_id) do update set
        last_seen = excluded.last_seen,
        total_entries = public.access_devices.total_entries + 1,
        last_path = excluded.last_path,
        user_agent = coalesce(excluded.user_agent, public.access_devices.user_agent);

    insert into public.access_sessions (device_id, session_id, started_at)
    values (p_device_id, p_session_id, v_now)
    on conflict (device_id, session_id) do nothing;

    update public.access_devices
    set total_sessions = (
        select count(*)::integer
        from public.access_sessions
        where access_sessions.device_id = p_device_id
    )
    where access_devices.device_id = p_device_id;

    insert into public.access_visits (device_id, session_id, visited_at, path, user_agent)
    values (p_device_id, p_session_id, v_now, left(p_path, 512), left(p_user_agent, 512));
end;
$$;

revoke all on function public.register_anonymous_access(text, text, text, text) from public;
grant execute on function public.register_anonymous_access(text, text, text, text) to anon, authenticated;

create or replace view public.access_monitor_summary as
select
    d.device_id,
    d.first_seen,
    d.last_seen,
    d.total_entries,
    d.total_sessions,
    count(distinct (v.visited_at at time zone 'utc')::date)::integer as active_days,
    round(d.total_entries::numeric / nullif(count(distinct (v.visited_at at time zone 'utc')::date), 0), 2) as entries_per_active_day,
    round(d.total_entries::numeric / nullif(d.total_sessions, 0), 2) as entries_per_session,
    d.last_path,
    d.user_agent
from public.access_devices d
left join public.access_visits v on v.device_id = d.device_id
group by d.device_id, d.first_seen, d.last_seen, d.total_entries, d.total_sessions, d.last_path, d.user_agent;

revoke all on table public.access_monitor_summary from anon, authenticated;

comment on view public.access_monitor_summary is
'Painel administrativo: consultar no SQL Editor do Supabase. Não expor esta view ao navegador.';
